//! TypeScript generation (contract 9).
//!
//! Generates one `.ts` file per exported type plus an `index.ts`, entirely in
//! memory, from the root [`Envelope`] and everything it references. The
//! checked-in copy lives in `apps/desktop/src/shared/engine-protocol/`; a test
//! fails when regenerating would change it, and the `pm-protocol-ts` binary
//! rewrites it.

use std::any::TypeId;
use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

use ts_rs::{Config, TS, TypeVisitor};

use crate::envelope::Envelope;

/// The checked-in output directory, relative to this crate's manifest.
pub const OUTPUT_DIR_FROM_MANIFEST: &str = "../../../apps/desktop/src/shared/engine-protocol";

/// The generated files' location in the repository.
pub fn output_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join(OUTPUT_DIR_FROM_MANIFEST)
}

const INDEX_HEADER: &str = "// Generated by engine/crates/pm-protocol (ts-rs). Do not edit by hand.\n\
// Regenerate: source engine/env.sh && cd engine && cargo run -p pm-protocol --bin pm-protocol-gen\n\
// Wire format: MessagePack maps with these field names (contract 9,\n\
// docs/engine/rfcs/09-protocol-codec.md). Every integer is a safe JS number;\n\
// every float is finite (no NaN or Infinity).\n";

fn config() -> Config {
    // Large integers must never appear: the protocol keeps every integer in
    // the safe range. "bigint" makes a stray u64 visible in review and in the
    // `no_bigint` test.
    Config::new().with_large_int("bigint")
}

struct Collector<'a> {
    cfg: &'a Config,
    seen: BTreeSet<TypeIdOrd>,
    files: BTreeMap<PathBuf, (String, String)>,
    error: Option<String>,
}

#[derive(PartialEq, Eq, PartialOrd, Ord)]
struct TypeIdOrd(String, TypeIdKey);

#[derive(PartialEq, Eq)]
struct TypeIdKey(TypeId);

impl PartialOrd for TypeIdKey {
    fn partial_cmp(&self, other: &Self) -> Option<std::cmp::Ordering> {
        Some(self.cmp(other))
    }
}

impl Ord for TypeIdKey {
    fn cmp(&self, other: &Self) -> std::cmp::Ordering {
        // TypeId is Ord.
        self.0.cmp(&other.0)
    }
}

impl Collector<'_> {
    fn add<T: TS + 'static + ?Sized>(&mut self) {
        if self.error.is_some() {
            return;
        }
        let Some(path) = T::output_path() else { return };
        let key = TypeIdOrd(
            std::any::type_name::<T>().to_owned(),
            TypeIdKey(TypeId::of::<T>()),
        );
        if !self.seen.insert(key) {
            return;
        }
        match T::export_to_string(self.cfg) {
            Ok(text) => {
                match self.files.get(&path) {
                    // ts-rs maps `serde_json::Value` and its helper alias to
                    // one file with one declaration; identical text is one type.
                    Some((_, existing)) if *existing == text => {}
                    Some((other, _)) => {
                        self.error = Some(format!(
                            "{} and {} both export to {}",
                            other,
                            std::any::type_name::<T>(),
                            path.display()
                        ));
                        return;
                    }
                    None => {
                        self.files
                            .insert(path, (std::any::type_name::<T>().to_owned(), text));
                    }
                }
            }
            Err(error) => {
                self.error = Some(format!("{}: {error}", std::any::type_name::<T>()));
                return;
            }
        }
        T::visit_dependencies(self);
    }
}

impl TypeVisitor for Collector<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        self.add::<T>();
    }
}

/// Generates every file, keyed by path relative to the output directory.
pub fn generate() -> Result<BTreeMap<PathBuf, String>, String> {
    let cfg = config();
    let mut collector = Collector {
        cfg: &cfg,
        seen: BTreeSet::new(),
        files: BTreeMap::new(),
        error: None,
    };
    collector.add::<Envelope>();
    if let Some(error) = collector.error {
        return Err(error);
    }
    let mut files: BTreeMap<PathBuf, String> = collector
        .files
        .into_iter()
        .map(|(path, (_, text))| (path, text))
        .collect();
    let mut index = String::from(INDEX_HEADER);
    index.push('\n');
    for path in files.keys() {
        let module = path.with_extension("");
        let name = module
            .file_name()
            .and_then(|n| n.to_str())
            .ok_or("bad file name")?;
        let module = module.to_str().ok_or("non-UTF-8 path")?.replace('\\', "/");
        index.push_str(&format!("export type {{ {name} }} from \"./{module}\";\n"));
    }
    files.insert(PathBuf::from("index.ts"), index);
    Ok(files)
}

/// Differences between generated files and a directory on disk.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct Drift {
    pub missing: Vec<PathBuf>,
    pub changed: Vec<PathBuf>,
    pub stale: Vec<PathBuf>,
}

impl Drift {
    pub fn is_empty(&self) -> bool {
        self.missing.is_empty() && self.changed.is_empty() && self.stale.is_empty()
    }
}

fn list_ts(dir: &Path, base: &Path, out: &mut Vec<PathBuf>) -> std::io::Result<()> {
    if !dir.exists() {
        return Ok(());
    }
    for entry in std::fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            list_ts(&path, base, out)?;
        } else if path.extension().is_some_and(|e| e == "ts")
            && !path.to_string_lossy().ends_with(".test.ts")
        {
            out.push(
                path.strip_prefix(base)
                    .expect("listed under base")
                    .to_path_buf(),
            );
        }
    }
    Ok(())
}

/// Compares generated files with `dir`. Hand-written `*.test.ts` files in
/// the directory are left alone.
pub fn drift(files: &BTreeMap<PathBuf, String>, dir: &Path) -> std::io::Result<Drift> {
    let mut drift = Drift::default();
    for (path, text) in files {
        match std::fs::read_to_string(dir.join(path)) {
            Ok(existing) if existing == *text => {}
            Ok(_) => drift.changed.push(path.clone()),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => drift.missing.push(path.clone()),
            Err(e) => return Err(e),
        }
    }
    let mut on_disk = Vec::new();
    list_ts(dir, dir, &mut on_disk)?;
    drift.stale = on_disk
        .into_iter()
        .filter(|p| !files.contains_key(p))
        .collect();
    drift.stale.sort();
    Ok(drift)
}

/// Writes generated files into `dir`, removing stale `.ts` files.
pub fn write(files: &BTreeMap<PathBuf, String>, dir: &Path) -> std::io::Result<Drift> {
    let before = drift(files, dir)?;
    for path in &before.stale {
        std::fs::remove_file(dir.join(path))?;
    }
    for (path, text) in files {
        let target = dir.join(path);
        if let Some(parent) = target.parent() {
            std::fs::create_dir_all(parent)?;
        }
        if std::fs::read_to_string(&target).ok().as_deref() != Some(text.as_str()) {
            std::fs::write(&target, text)?;
        }
    }
    Ok(before)
}
