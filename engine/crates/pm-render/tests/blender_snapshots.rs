//! Section 25's "Blender snapshots" class on the parity corpus: for every
//! 3D corpus frame with Blender on (final and preview, the exporter's
//! opaque and alpha passes, every shutter sample, nested compositions), the
//! snapshot `pm_render::blender` builds equals today's `renderSnapshot`
//! output — geometry within 1e-6; materials, maps, blocks, the background
//! list, camera, lights, settings, and environment identical; asset bytes
//! equal (SHA-256) — and the frames `blenderFrameRequests` lists equal the
//! engine's (`blender::frames`): composition, time bit for bit, and size.
//!
//! The capture turned `render3d` on in memory for every composition with 3D
//! objects (`compositions`, with `settings`); this test does the same to
//! the loaded document.
//!
//! Nothing is allowed to differ or to be skipped (amendments 21 and 22): a
//! snapshot the engine does not build is a failure, as is any asset that
//! differs. Source materials
//! follow amendment 14's fix (`sourceMaterialSnapshot`), which corpus v1
//! records; v0 recorded the throw instead.
//!
//! `PM_ENGINE_CORPUS` picks the captures (comma-separated; default: the
//! newest `v1-*` and the newest `threed-2*` capture, which has the level 1 map
//! classes); `PM_BLENDER_ONLY` limits to project names with a prefix.
//!
//! AVIF and SVG maps take the PNG the editor window's Chromium draws
//! (decision THREED-2). Those PNGs are corpus inputs, content-addressed by the
//! original file's SHA-256, in `blender-chromium-pngs/` at the corpus root
//! (`PM_BLENDER_CHROMIUM_PNGS` overrides the directory). A missing PNG fails
//! the test and leaves a `<sha>.json` need beside it; generate the PNGs with
//! `pm-electron-lock bun engine/crates/pm-render/tools/blender-png/run.ts
//! --needs <directory>` and run the test again (docs/engine/blender.md).

