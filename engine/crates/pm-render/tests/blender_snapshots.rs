const PASSES: [&str; 4] = ["final", "preview", "export", "exportAlpha"];

/// Independent inputs generated by tools/blender-png/run.ts from original
/// media in the app's Electron Chromium. The legacy snapshot's recorded PNG
/// is used only as the expected output below, never as the resolver input.
struct ChromiumPngResolver<'a> {
    files: &'a pm_render::MapResolver,
    dir: &'a std::path::Path,
}

/// Where the Chromium Blender PNGs live: `PM_BLENDER_CHROMIUM_PNGS`, else
/// `blender-chromium-pngs/` at the corpus root (beside the captures, so the
/// captures' own file lists stay verified).
fn chromium_png_dir() -> std::path::PathBuf {
    std::env::var_os("PM_BLENDER_CHROMIUM_PNGS")
        .map(std::path::PathBuf::from)
        .unwrap_or_else(|| corpus_root().join("blender-chromium-pngs"))
}

/// The failure note for a snapshot the engine did not build because a
/// Chromium PNG input is missing.
fn generation_hint(why: &str, dir: &std::path::Path) -> String {
    if why.contains("did not provide the exact Blender PNG") {
        format!(
            " (generate the missing inputs: ~/Library/Caches/powermove-engine/bin/pm-electron-lock bun engine/crates/pm-render/tools/blender-png/run.ts --needs {:?})",
            dir
        )
    } else {
        String::new()
    }
}

impl AssetResolver for ChromiumPngResolver<'_> {
    fn path(&self, asset: &str, record: Option<&Node>) -> Option<std::path::PathBuf> {
        self.files.path(asset, record)
    }

    fn blender_png(
        &self,
        _asset: &str,
        source: &std::path::Path,
    ) -> Result<Option<Arc<Vec<u8>>>, String> {
        let png = self.dir.join(format!("{}.png", content_sha(source)?));
        if png.exists() {
            return std::fs::read(png)
                .map(|bytes| Some(Arc::new(bytes)))
                .map_err(|e| e.to_string());
        }
        // The builder stops at the first missing PNG; record every
        // browser-decoded still of the project so one generation run covers
        // them all.
        std::fs::create_dir_all(self.dir).map_err(|e| e.to_string())?;
        let mut sources: Vec<&std::path::Path> =
            self.files.paths.values().map(|p| p.as_path()).collect();
        sources.push(source);
        for path in sources {
            let Ok(head) = std::fs::read(path) else {
                continue;
            };
            let browser = matches!(
                pm_media::image::sniff(&head[..head.len().min(4096)]),
                pm_media::image::ImageFormat::Avif | pm_media::image::ImageFormat::Svg
            );
            let content = content_sha(path)?;
            if !browser || self.dir.join(format!("{content}.png")).exists() {
                continue;
            }
            let need = serde_json::json!({ "content": content, "source": path.to_string_lossy() });
            std::fs::write(self.dir.join(format!("{content}.json")), need.to_string())
                .map_err(|e| e.to_string())?;
        }
        Ok(None)
    }
}

fn content_sha(path: &std::path::Path) -> Result<String, String> {
    let original = std::fs::read(path).map_err(|e| format!("{}: {e}", path.display()))?;
    Ok(Sha256::digest(&original)
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect())
}

fn get<'a>(v: &'a Value, k: &str) -> Option<&'a Value> {
    v.get(k)
}

fn s(v: Option<&Value>) -> String {
    v.and_then(Value::as_str).unwrap_or("").to_owned()
}

fn n(v: Option<&Value>) -> Option<f64> {
    v.and_then(Value::as_f64)
}

/// `loaded.json` with `render3d = settings` on `compositions`.
fn with_blender(loaded: &Value, compositions: &[String], settings: &Value) -> Value {
    let mut root = loaded.clone();
    let open = s(get(&root, "compId")).to_owned();
    let open = if open.is_empty() {
        s(get(&root, "id"))
    } else {
        open
    };
    let Value::Object(map) = &mut root else {
        panic!("root")
    };
    for c in compositions {
        if *c == open && map.get("layers").is_some() {
            map.insert("render3d", settings.clone());
        } else if let Some(Value::Object(comps)) = map.get_mut("comps")
            && let Some(Value::Object(comp)) = comps.get_mut(c)
        {
            comp.insert("render3d", settings.clone());
        }
    }
    root
}

#[derive(Default)]
struct Totals {
    snapshots: usize,
    equal: usize,
    geometry_values: usize,
    geometry_max: f64,
    exact_values: usize,
    frame_lists: usize,
    failed: Vec<String>,
    /// Snapshots whose converted PNG textures equal today's by pixels.
    converted: usize,
}

#[derive(Debug, PartialEq, Eq)]
struct PngPixels {
    width: u32,
    height: u32,
    rgba: Vec<u16>,
}

/// Decode every PNG channel and depth Blender reads. Never treat two
/// unhandled layouts (or two decode failures) as equal.
fn png_pixels(bytes: &[u8]) -> Option<PngPixels> {
    let mut decoder = png::Decoder::new(std::io::Cursor::new(bytes));
    decoder.set_transformations(png::Transformations::EXPAND | png::Transformations::ALPHA);
    let mut reader = decoder.read_info().ok()?;
    let mut buf = vec![0; reader.output_buffer_size()?];
    let info = reader.next_frame(&mut buf).ok()?;
    buf.truncate(info.buffer_size());
    let samples: Vec<u16> = match info.bit_depth {
        png::BitDepth::Eight => buf.into_iter().map(|v| u16::from(v) * 257).collect(),
        png::BitDepth::Sixteen => buf
            .chunks_exact(2)
            .map(|v| u16::from_be_bytes([v[0], v[1]]))
            .collect(),
        _ => return None,
    };
    let rgba = match info.color_type {
        png::ColorType::Rgba => samples,
        png::ColorType::Rgb => samples
            .chunks_exact(3)
            .flat_map(|p| [p[0], p[1], p[2], 65535])
            .collect(),
        png::ColorType::GrayscaleAlpha => samples
            .chunks_exact(2)
            .flat_map(|p| [p[0], p[0], p[0], p[1]])
            .collect(),
        png::ColorType::Grayscale => samples.iter().flat_map(|&p| [p, p, p, 65535]).collect(),
        _ => return None,
    };
    Some(PngPixels {
        width: info.width,
        height: info.height,
        rgba,
    })
}

#[test]
fn snapshots_equal_todays_render_snapshot() {
    let captures: Vec<std::path::PathBuf> = match std::env::var("PM_ENGINE_CORPUS") {
        Ok(p) => p.split(',').map(std::path::PathBuf::from).collect(),
        Err(_) => [newest_capture("v1-"), newest_capture("threed-2")]
            .into_iter()
            .flatten()
            .collect(),
    };
    if captures.is_empty() {
        eprintln!("no parity corpus capture found; set PM_ENGINE_CORPUS to run this comparison");
        return;
    }
    let only = std::env::var("PM_BLENDER_ONLY").ok();
    let chromium_pngs = chromium_png_dir();
    let mut t = Totals::default();
    for (capture, dir) in captures
        .iter()
        .flat_map(|c| projects(c).into_iter().map(move |d| (c.clone(), d)))
    {
        let blender = dir.join("blender");
        if !blender.is_dir() {
            continue;
        }
        let p = load_project(&capture, &dir);
        if only.as_deref().is_some_and(|o| !p.name.starts_with(o)) {
            continue;
        }
        let mut files: Vec<_> = std::fs::read_dir(&blender)
            .unwrap()
            .flatten()
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|x| x == "json"))
            .collect();
        files.sort();
        let loaded = read_json(&dir.join("loaded.json"));
        for file in files {
            let record = read_json(&file);
            assert_eq!(s(get(&record, "format")), "powermove-corpus-blender");
            let compositions: Vec<String> = get(&record, "compositions")
                .and_then(Value::as_array)
                .map(|a| a.iter().map(|c| s(Some(c))).collect())
                .unwrap_or_default();
            let settings = get(&record, "settings").cloned().unwrap();
            let doc =
                pm_model::Document::new(Some(with_blender(&loaded, &compositions, &settings)), 1);
            let time = n(get(&record, "time")).unwrap();
            let mut ev = Evaluator::new().with_expressions(Arc::new(PmExprEngine));
            let root = Comp::resolve(&doc, &p.composition).unwrap();
            for pass in PASSES {
                let Some(entry) = get(&record, pass) else {
                    continue;
                };
                if let Some(e) = get(entry, "error") {
                    t.failed.push(format!(
                        "{}/{pass}: the capture recorded an error: {}",
                        p.name,
                        s(Some(e))
                    ));
                    continue;
                }
                let snapshots = get(entry, "snapshots")
                    .and_then(Value::as_array)
                    .cloned()
                    .unwrap_or_default();
                // Frames: the engine's walk lists the same frames.
                if pass != "preview" {
                    let opts = get(entry, "options");
                    let options = FrameOptions {
                        width: n(opts.and_then(|o| get(o, "width"))).map(|v| v as u32),
                        height: n(opts.and_then(|o| get(o, "height"))).map(|v| v as u32),
                        motion_blur: !matches!(
                            opts.and_then(|o| get(o, "mblur")),
                            Some(Value::Bool(false))
                        ),
                        samples: n(opts.and_then(|o| get(o, "mbSamples"))).map_or(10, |v| v as u32),
                        shutter: n(opts.and_then(|o| get(o, "shutter"))),
                    };
                    let frames = frame_requests(&mut ev, &root, &root, time, options)
                        .unwrap()
                        .unwrap();
                    let want: Vec<(String, u64, u32, u32)> = snapshots
                        .iter()
                        .map(|x| {
                            let r = get(x, "request").unwrap();
                            (
                                s(get(r, "comp")),
                                n(get(r, "time")).unwrap().to_bits(),
                                n(get(r, "width")).unwrap() as u32,
                                n(get(r, "height")).unwrap() as u32,
                            )
                        })
                        .collect();
                    let got: Vec<(String, u64, u32, u32)> = frames
                        .iter()
                        .map(|f| {
                            (
                                f.composition().to_owned(),
                                f.time.to_bits(),
                                f.width,
                                f.height,
                            )
                        })
                        .collect();
                    if got == want {
                        t.frame_lists += 1;
                    } else {
                        t.failed.push(format!(
                            "{}/{pass} t={time}: frames differ: today {want:?}, engine {got:?}",
                            p.name
                        ));
                    }
                }
                for x in &snapshots {
                    let r = get(x, "request").unwrap();
                    let comp_id = s(get(r, "comp"));
                    let comp = Comp::resolve(&doc, &comp_id).unwrap();
                    let preview = matches!(get(r, "preview"), Some(Value::Bool(true)));
                    let w = n(get(r, "width"))
                        .unwrap_or_else(|| pm_eval::node::to_number(comp.member("w")));
                    let h = n(get(r, "height"))
                        .unwrap_or_else(|| pm_eval::node::to_number(comp.member("h")));
                    let frame = BlenderFrame {
                        composition_path: vec![comp_id.clone()],
                        time: n(get(r, "time")).unwrap(),
                        width: w as u32,
                        height: h as u32,
                        shutter: None,
                        preview,
                    };
                    let label = format!("{}/{pass} {comp_id} t={}", p.name, frame.time);
                    t.snapshots += 1;
                    let mut scope = pm_eval::Scope::new(&mut ev, &comp, &root);
                    let resolver = ChromiumPngResolver {
                        files: &p.resolver,
                        dir: &chromium_pngs,
                    };
                    let built =
                        build(&mut scope, &frame, &resolver, &SnapshotOptions::default()).unwrap();
                    let snapshot = match built {
                        Ok(s) => s,
                        Err(why) => {
                            let hint = generation_hint(&why, &chromium_pngs);
                            t.failed.push(format!("{label}: not built: {why}{hint}"));
                            continue;
                        }
                    };
                    let mut today = get(x, "snapshot").unwrap().clone();
                    // All captured fields remain compared. Add the new output
                    // policy from the original layer compatibility, independently
                    // of the snapshot builder's metadata.
                    let compatible: Vec<Value> = get(&today, "objects")
                        .and_then(Value::as_array)
                        .into_iter()
                        .flatten()
                        .filter_map(|object| {
                            let id = s(get(object, "id"));
                            let layer = scope.layers().iter().find(|l| {
                                pm_eval::node::string(pm_eval::node::member(Some(l), "id"))
                                    .is_some_and(|name| name.to_string_lossy() == id)
                            });
                            let level2 = layer.is_some_and(|l| {
                                pm_eval::node::to_number(pm_eval::node::member(Some(l), "compat"))
                                    >= 2.0
                            });
                            (!level2).then(|| Value::String(id.into()))
                        })
                        .collect();
                    if !compatible.is_empty() {
                        today
                            .as_object_mut()
                            .unwrap()
                            .insert("compatibilityLayers", Value::Array(compatible));
                    }
                    let c: Comparison = compare(&today, &snapshot.json);
                    // Assets: id, name, and bytes.
                    let want: Vec<(String, String, String)> = get(x, "assets")
                        .and_then(Value::as_array)
                        .into_iter()
                        .flatten()
                        .map(|a| (s(get(a, "id")), s(get(a, "name")), s(get(a, "sha256"))))
                        .collect::<std::collections::BTreeSet<_>>()
                        .into_iter()
                        .collect();
                    let got: Vec<(String, String, String)> = snapshot
                        .assets
                        .iter()
                        .map(|a| {
                            (
                                a.id.clone(),
                                a.name.clone(),
                                a.sha256.iter().map(|b| format!("{b:02x}")).collect(),
                            )
                        })
                        .collect::<std::collections::BTreeSet<_>>()
                        .into_iter()
                        .collect();
                    t.geometry_values += c.geometry_values;
                    t.exact_values += c.exact_values;
                    t.geometry_max = t.geometry_max.max(c.geometry_max);
                    // Converted images (`<id>.png` today made by a canvas's
                    // `toBlob`): the PNG container bytes are each encoder's
                    // own, so they are compared by decoded pixels, which is
                    // what Blender reads.
                    let converted_equal = want.len() == got.len()
                        && want.iter().zip(&got).all(|(w, g)| {
                            w == g
                                || (w.0 == g.0
                                    && w.1 == g.1
                                    && w.1.ends_with(".png")
                                    && snapshot.assets.iter().any(|a| {
                                        a.id == g.0
                                            && matches!(
                                                a.bytes,
                                                pm_blender::snapshot::AssetBytes::Bytes(_)
                                            )
                                            && png_pixels(&a.bytes.read().unwrap()).is_some_and(
                                                |ours| {
                                                    Some(ours)
                                                        == std::fs::read(
                                                            blender
                                                                .join("assets")
                                                                .join(format!("{}.png", w.2)),
                                                        )
                                                        .ok()
                                                        .and_then(|b| png_pixels(&b))
                                                },
                                            )
                                    }))
                        });
                    if converted_equal && want != got {
                        t.converted += 1;
                    }
                    if c.equal() && (want == got || converted_equal) {
                        t.equal += 1;
                    } else {
                        let mut lines = vec![format!("{label}:")];
                        for d in c.differences.iter().take(12) {
                            lines.push(format!(
                                "  {}: today {} engine {}",
                                d.path, d.today, d.engine
                            ));
                        }
                        if want != got {
                            for (w, g) in want.iter().zip(&got).filter(|(w, g)| w != g) {
                                let ours = snapshot
                                    .assets
                                    .iter()
                                    .find(|a| a.id == g.0)
                                    .and_then(|a| png_pixels(&a.bytes.read().unwrap()));
                                let today = std::fs::read(
                                    blender.join("assets").join(format!("{}.png", w.2)),
                                )
                                .ok()
                                .and_then(|b| png_pixels(&b));
                                let diff = match (&ours, &today) {
                                    (Some(a), Some(b))
                                        if a.width == b.width && a.height == b.height =>
                                    {
                                        let (a, b) = (&a.rgba, &b.rgba);
                                        let d = a
                                            .iter()
                                            .zip(b)
                                            .map(|(x, y)| x.abs_diff(*y))
                                            .max()
                                            .unwrap_or(0);
                                        let n = a
                                            .chunks(4)
                                            .zip(b.chunks(4))
                                            .filter(|(x, y)| x != y)
                                            .count();
                                        format!(
                                            "max {:.3} CV, {n} pixels differ",
                                            f64::from(d) / 257.0
                                        )
                                    }
                                    _ => format!(
                                        "ours {:?} today {:?}",
                                        ours.as_ref().map(|o| (o.width, o.height, o.rgba.len())),
                                        today.as_ref().map(|o| (o.width, o.height, o.rgba.len()))
                                    ),
                                };
                                if ours != today
                                    && let Ok(dir) = std::env::var("PM_BLENDER_DIFFS")
                                {
                                    let dir = std::path::Path::new(&dir);
                                    std::fs::create_dir_all(dir).unwrap();
                                    let id: String = g
                                        .0
                                        .chars()
                                        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
                                        .collect();
                                    if let Some(asset) =
                                        snapshot.assets.iter().find(|a| a.id == g.0)
                                    {
                                        std::fs::write(
                                            dir.join(format!("{id}-engine.png")),
                                            asset.bytes.read().unwrap().as_slice(),
                                        )
                                        .unwrap();
                                    }
                                    let bytes = std::fs::read(
                                        blender.join("assets").join(format!("{}.png", w.2)),
                                    )
                                    .unwrap();
                                    std::fs::write(dir.join(format!("{id}-today.png")), bytes)
                                        .unwrap();
                                }
                                lines.push(format!(
                                    "  asset {} {}: today {} engine {} ({diff})",
                                    w.0, w.1, w.2, g.2
                                ));
                            }
                        }
                        t.failed.push(lines.join("\n"));
                    }
                }
            }
        }
    }
    eprintln!(
        "Blender snapshots: {} compared, {} equal ({} with converted textures equal by pixels); {} frame lists equal; geometry {} values, max |Δ| {:e}; {} exact values",
        t.snapshots,
        t.equal,
        t.converted,
        t.frame_lists,
        t.geometry_values,
        t.geometry_max,
        t.exact_values
    );
    assert!(
        t.failed.is_empty(),
        "{} failures:\n{}",
        t.failed.len(),
        t.failed.join("\n")
    );
    if only.is_none() {
        assert!(t.equal > 0, "nothing compared");
    }
    let _ = (JsString::new(), Map::new());
}

#[test]
fn tiff_renditions_equal_todays_blender_textures_at_full_depth() {
    let Some(capture) = newest_capture("threed-2") else {
        return;
    };
    let dir = capture.join("projects/3d/maps-level1");
    let p = load_project(&capture, &dir);
    let record = read_json(&dir.join("blender/t0.000000.json"));
    let entry = record
        .get("final")
        .unwrap()
        .get("snapshots")
        .unwrap()
        .as_array()
        .unwrap()
        .first()
        .unwrap();
    let request = entry.get("request").unwrap();
    let loaded = read_json(&dir.join("loaded.json"));
    let composition = s(get(request, "comp"));
    let doc = pm_model::Document::new(
        Some(with_blender(
            &loaded,
            std::slice::from_ref(&composition),
            record.get("settings").unwrap(),
        )),
        1,
    );
    let comp = Comp::resolve(&doc, &composition).unwrap();
    let mut ev = Evaluator::new().with_expressions(Arc::new(PmExprEngine));
    let mut scope = pm_eval::Scope::new(&mut ev, &comp, &comp);
    let frame = BlenderFrame {
        composition_path: vec![composition],
        time: 0.0,
        width: pm_eval::node::to_number(comp.member("w")) as u32,
        height: pm_eval::node::to_number(comp.member("h")) as u32,
        shutter: None,
        preview: false,
    };
    // The level 1 maps include AVIF classes, which take Chromium's PNG
    // exactly as the full comparison above does.
    let chromium_pngs = chromium_png_dir();
    let resolver = ChromiumPngResolver {
        files: &p.resolver,
        dir: &chromium_pngs,
    };
    let built = build(&mut scope, &frame, &resolver, &SnapshotOptions::default())
        .unwrap()
        .unwrap_or_else(|why| {
            panic!(
                "maps-level1 not built: {why}{}",
                generation_hint(&why, &chromium_pngs)
            )
        });
    let mut compared = 0;
    for asset in &built.assets {
        let source = loaded
            .get("assets")
            .and_then(|a| a.get(asset.id.as_str()))
            .unwrap();
        if source.get("format").and_then(Value::as_str) != Some("tiff") {
            continue;
        }
        let want = entry
            .get("assets")
            .unwrap()
            .as_array()
            .unwrap()
            .iter()
            .find(|a| a.get("id").and_then(Value::as_str) == Some(asset.id.as_str()))
            .unwrap();
        let bytes = std::fs::read(dir.join("blender/assets").join(format!(
            "{}.png",
            want.get("sha256").and_then(Value::as_str).unwrap()
        )))
        .unwrap();
        let today = png_pixels(&bytes).unwrap();
        assert_eq!(
            png_pixels(&asset.bytes.read().unwrap()).unwrap(),
            today,
            "{}",
            asset.id
        );
        compared += 1;
    }
    assert_eq!(compared, 6);
}
