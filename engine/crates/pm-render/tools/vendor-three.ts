/**
 * Vendors three.js r180's GLSL (ShaderChunk from the built module the app
 * bundles, which includes the ShaderLib programs as `<name>_vert` /
 * `<name>_frag`) into src/three/r180/ as one file
 * per chunk, exactly as three.js holds the strings, plus chunks.rs (the
 * table the program generator resolves `#include <name>` against).
 * Amendment 11: the native 3D pass compiles three.js's own GLSL.
 *
 *   bun engine/crates/pm-render/tools/vendor-three.ts
 */
import { mkdirSync, readdirSync, rmSync, writeFileSync, readFileSync } from 'node:fs';
import path from 'node:path';

const here = path.dirname(new URL(import.meta.url).pathname);
const repo = path.join(here, '../../../..');
const three = path.join(repo, 'apps/desktop/node_modules/three');
const version = JSON.parse(readFileSync(path.join(three, 'package.json'), 'utf8')).version;
if (version !== '0.180.0') throw new Error(`three.js ${version} is installed; the native 3D pass ports r180`);
// The built module the app bundles (`three` resolves to build/three.module.js): its
// chunks are the shipped ones, comments and blank lines already stripped by
// three.js's build, so the programs equal what WebGL receives in the app.
const { ShaderChunk } = await import(path.join(three, 'build/three.module.js'));
const out = path.join(here, '../src/three/r180');
for (const file of readdirSync(out)) if (file.endsWith('.glsl')) rmSync(path.join(out, file));
mkdirSync(out, { recursive: true });
const names = Object.keys(ShaderChunk).sort();
for (const name of names) writeFileSync(path.join(out, `${name}.glsl`), ShaderChunk[name]);
writeFileSync(path.join(out, 'LICENSE'), readFileSync(path.join(three, 'LICENSE'), 'utf8'));
const table = [
  '// Generated by tools/vendor-three.ts from three.js r180 (MIT, see r180/LICENSE). Do not edit.',
  '',
  '/// three.js r180 `ShaderChunk`, by name.',
  'pub const CHUNKS: &[(&str, &str)] = &[',
  ...names.map(n => `    (${JSON.stringify(n)}, include_str!("r180/${n}.glsl")),`),
  '];',
  '',
].join('\n');
writeFileSync(path.join(here, '../src/three/chunks.rs'), table);
console.log(`${names.length} chunks from three.js ${version}`);
