//! Shape, path, and mask geometry for the native engine (sections 10 and 31).
//!
//! Exact ports of today's Canvas2D geometry onto [`kurbo`], producing
//! [`kurbo::BezPath`] outlines plus the bounds and bitmap sizes today's
//! renderer computes, ready for Vello:
//!
//! - [`shape`]: rect with per-corner radius and smoothing ([`corner`]),
//!   ellipse, polygon, star (inner ratio 0.46), line (`legacy/gl/raster.ts`,
//!   `legacy/gl/corner-geometry.ts`, `legacy/gl/shape-raster-window.ts`).
//! - [`path`]: editable cubic paths with per-vertex tangents, trim start, end,
//!   and offset, group parenting, and the repeater up to 256 copies
//!   (`legacy/core/vector-paths.ts`).
//! - [`mask`]: parametric rectangle and ellipse masks (feather, rotation, add
//!   and subtract, the 8-mask GPU limit) and bezier path masks
//!   (`legacy/gl/compositor.ts`, `legacy/gl/shaders.ts`).
//!
//! Determinism: every transcendental goes through `libm` and every
//! JavaScript numeric rule the legacy code relies on is reproduced in [`js`],
//! so native and wasm32 builds produce identical bits. The `tests/vectors`
//! suite replays cases generated by running the TypeScript under bun.

