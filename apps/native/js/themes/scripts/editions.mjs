// Explicit snapshot generation; --check never writes. No app runtime imports this.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import {
  appRootCss,
  nativeSnapshots,
  panelSources,
  variableUsage,
  reference,
} from "./edition-inputs.mjs";
const folder = new URL("../", import.meta.url);
const check = process.argv.includes("--check");
function artifact(path, text) {
  const url = new URL(path, folder);
  if (check) {
    if (readFileSync(url, "utf8") !== text)
      throw Error(`Stale edition artifact: ${path}`);
  } else {
    mkdirSync(new URL(".", url), { recursive: true });
    writeFileSync(url, text);
  }
}
const json = (data) => JSON.stringify(data, null, 2) + "\n";
artifact(
  "edition-foundation.mjs",
  `// Public v1.2.0 app root variables; generated by scripts/editions.mjs.\nexport const APP_ROOT_CSS = ${JSON.stringify(appRootCss())};\n`,
);
const { createCompatEdition } = await import("../editions.mjs");
const snapshots = nativeSnapshots();
artifact("fixtures/native-tokens-v1.json", json(snapshots));
const usages = panelSources()
  .map(variableUsage)
  .filter((source) => source.reads.length);
artifact(
  "fixtures/builtin-variable-reads.json",
  json({ reference, sources: usages }),
);
const editions = snapshots.map((native) => createCompatEdition(native));
artifact(
  "editions/v1/manifest.json",
  json({
    version: 1,
    reference,
    editions: editions.map((edition) => {
      const file = edition.id.split("/")[1] + ".css";
      artifact(`editions/v1/${file}`, edition.stylesheet);
      return {
        id: edition.id,
        scheme: edition.scheme,
        accessibility: edition.accessibility,
        file,
        sha256: createHash("sha256").update(edition.stylesheet).digest("hex"),
      };
    }),
  }),
);
console.log(
  `Compat editions: ${editions.length}; built-in read sites: ${usages.reduce((n, source) => n + source.reads.length, 0)}`,
);
