// Test/build tooling only. Runtime modules do not import Node APIs.
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../../../../", import.meta.url));
const folder = fileURLToPath(new URL("../", import.meta.url));
const reference = "07ed5fa17ee640659cb075f9cad1af2095011d60";
const doc = readFileSync(`${root}/docs/native/t1-themes.md`, "utf8");
const rows = [];
let source = "";
for (const line of doc.split("\n")) {
  if (line.startsWith("### `")) source = line.split("`")[1];
  if (!/^\| \d+ \|/.test(line)) continue;
  const cells = line
    .split(/(?<!\\)\|/)
    .slice(1, -1)
    .map((cell) => cell.trim().replace(/\\\|/g, "|"));
  if (cells.length !== 6) continue;
  const [number, selector, conditions, surface, disposition, properties] =
    cells;
  rows.push({
    source,
    line: Number(number),
    selector: selector.slice(1, -1),
    conditions: conditions === "—" ? null : conditions,
    surface,
    class: disposition,
    properties: [...properties.matchAll(/`([^`]+)`/g)].map((match) => match[1]),
  });
}
if (
  rows.length !== 3329 ||
  rows.filter((row) => row.class === "C").length !== 19
)
  throw new Error(
    "T1 inventory changed; review the baseline before regenerating",
  );
const catalog = {
  reference,
  inventorySha256: createHash("sha256").update(doc).digest("hex"),
  rows,
};
const foundation = execFileSync(
  "git",
  ["show", `${reference}:packages/tokens/tokens.css`],
  { cwd: root, encoding: "utf8" },
);
const builtins = execFileSync(
  "git",
  ["show", `${reference}:apps/desktop/src/extensions/theme-default/index.ts`],
  { cwd: root, encoding: "utf8" },
);
const definitionText = builtins.slice(
  builtins.indexOf("= [") + 2,
  builtins.indexOf("\n];") + 2,
);
// Frozen public source only; never evaluate an installed or imported extension.
const definitions = Function(`"use strict"; return (${definitionText});`)();
const artifacts = [
  [
    "fixtures/t1-catalog.json",
    '{\n  "reference": ' +
      JSON.stringify(catalog.reference) +
      ',\n  "inventorySha256": ' +
      JSON.stringify(catalog.inventorySha256) +
      ',\n  "rows": [\n' +
      rows.map((row) => "    " + JSON.stringify(row)).join(",\n") +
      "\n  ]\n}\n",
  ],
  ["fixtures/builtins.json", JSON.stringify(definitions, null, 2) + "\n"],
  [
    "foundation.mjs",
    "// Public v1.2.0 foundation; generated by scripts/catalog.mjs.\nexport const FOUNDATION_CSS = " +
      JSON.stringify(foundation) +
      ";\n",
  ],
];
for (const [path, text] of artifacts) {
  if (process.argv.includes("--check")) {
    if (readFileSync(`${folder}/${path}`, "utf8") !== text)
      throw new Error(`Stale artifact: ${path}`);
  } else writeFileSync(`${folder}/${path}`, text);
}
console.log(
  `T1: ${rows.length} occurrences, ${rows.filter((row) => row.class === "T").length} native, 19 compat; frozen foundation and built-ins verified`,
);
